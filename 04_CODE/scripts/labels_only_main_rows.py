"""Camera-ready addition (no new experiments): main-table metrics for the labels-only logistic baseline,
computed from the existing raw ablation runs 05_RESULTS/final/raw/runs_abl_labels_only.csv, with the same
aggregation as 04_CODE/scripts/analyze.py. Also re-derives the primary rows as a consistency check.
Output: 08_CAMERA_READY/ (or 05_RESULTS/camera_ready_extra/ in the public package): labels_only_*.csv, camera_ready_numbers.tex, tab_main_cr.tex"""
import sys
from pathlib import Path
import numpy as np, pandas as pd
ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "08_CAMERA_READY" if (ROOT / "08_CAMERA_READY").exists() else ROOT / "05_RESULTS" / "camera_ready_extra"
MANU = OUT / "manuscript" if (ROOT / "08_CAMERA_READY").exists() else OUT
OUT.mkdir(parents=True, exist_ok=True); MANU.mkdir(parents=True, exist_ok=True)
sys.path.insert(0, str(ROOT / "04_CODE"))
from gridbench.stats import cell_means, hier_bootstrap, method_label
import json
cfg = json.loads((ROOT/"04_CODE"/"config"/"frozen_config.json").read_text()) if (ROOT/"04_CODE"/"config"/"frozen_config.json").exists() else None
reps, seed = 10000, None
from gridbench.config import load_config
cfg = load_config(); reps, seed = cfg["ablations"]["bootstrap_reps"], cfg["ablations"]["bootstrap_seed"]
COLS = ["ap","auroc","tpr_at_fpr","precision","recall","f1","false_alerts_per_week","event_detection_rate","event_delay_h_mean"]
def agg(path, labels):
    d = pd.read_csv(path); d["mlabel"] = method_label(d)
    cm = cell_means(d, COLS); cm = cm[cm.condition == "none"]
    rows = []
    for m in labels:
        x = cm[cm.mlabel == m]
        r = {"method": m, "n_cells": len(x)}
        for c in COLS: r[c] = x.groupby("ba")[c].mean().mean()
        for c in ("ap","event_detection_rate"):
            _, lo, hi = hier_bootstrap(x[["ba","seed",c]], c, reps, seed); r[c+"_lo"], r[c+"_hi"] = lo, hi
        rows.append(r)
    return pd.DataFrame(rows)
raw = ROOT/"05_RESULTS"/"final"/"raw"
lo = agg(raw/"runs_abl_labels_only.csv", [f"labels_only_B{b}" for b in (8,32,128)])
chk = agg(raw/"runs_primary.csv", ["stat","pu_B128"])
ref = pd.read_csv(ROOT/"05_RESULTS"/"final"/"tables"/"table_main_none.csv").set_index("method")
for _, r in chk.iterrows():
    assert abs(r.ap-ref.loc[r.method,"ap"])<1e-9 and abs(r.event_detection_rate-ref.loc[r.method,"event_detection_rate"])<1e-9, r.method
    assert abs(r.ap_lo-ref.loc[r.method,"ap_lo"])<1e-9, "bootstrap mismatch"
print("consistency check vs table_main_none.csv: OK")
lo.to_csv(OUT/"labels_only_main_rows.csv", index=False)
print(lo.round(3).to_string())

# ---- paired comparisons and family/authority breakdown for the labels-only baseline (existing runs only)
from gridbench.stats import paired_difference
raw_all = pd.concat([pd.read_csv(raw/"runs_primary.csv"), pd.read_csv(raw/"runs_abl_labels_only.csv")], ignore_index=True)
raw_all["mlabel"] = method_label(raw_all)
fam = ["ap_flatline","ap_spike","ap_level_shift","ap_drift","ap_timing","edr_flatline","edr_spike","edr_level_shift","edr_drift","edr_timing"]
acm = cell_means(raw_all, ["ap","event_detection_rate"] + fam)
out = []
for a, b, met in [("labels_only_B128","stat","ap"),("labels_only_B128","stat","event_detection_rate"),
                  ("labels_only_B128","pu_B128","ap"),("labels_only_B128","pu_B128","event_detection_rate"),
                  ("labels_only_B128","iforest","ap"),("labels_only_B32","pu_B32","ap")]:
    out.append(paired_difference(acm, a, b, met, reps, seed, ["none"]))
pd.DataFrame(out).to_csv(OUT/"labels_only_paired.csv", index=False)
print(pd.DataFrame(out)[["a","b","metric","mean_diff","ci_lo","ci_hi","n_ba_positive","n_cells"]].round(3).to_string())
n = acm[acm.condition=="none"]
fm = n.groupby(["mlabel"])[fam].mean().loc[["stat","iforest","pu_B128","labels_only_B32","labels_only_B128"]]
print(fm.round(3).T.to_string())
fm.to_csv(OUT/"labels_only_family.csv")
print(n[n.mlabel.isin(["labels_only_B128","pu_B128","stat"])].groupby(["mlabel","ba"])["ap"].mean().unstack(0).round(3))

# ---- emit LaTeX macros (\crn{key}) and table rows so that no number is typed by hand
def f3(v): return ("$-$" if v < 0 else "") + f"{abs(v):.3f}"
def f2(v): return f"{v:.2f}"
K = {}
for _, r in lo.iterrows():
    b = r.method.split("_B")[1]
    for c in COLS + ["ap_lo","ap_hi","event_detection_rate_lo","event_detection_rate_hi"]:
        K[f"lo{b}_{c}"] = r[c]
for _, r in pd.DataFrame(out).iterrows():
    k = f"pair_{r.a}_{r.b}_{r.metric}"
    K[k+"_diff"], K[k+"_lo"], K[k+"_hi"], K[k+"_nba"] = r.mean_diff, r.ci_lo, r.ci_hi, r.n_ba_positive
for m, short in (("labels_only_B128","lo128"),("labels_only_B32","lo32")):
    for c in fam: K[f"{short}_{c}"] = fm.loc[m, c]
pba = n[n.mlabel=="labels_only_B128"].groupby("ba")["ap"].mean()
for ba, v in pba.items(): K[f"lo128_ap_{ba}"] = v
lines = ["% generated by 08_CAMERA_READY/scripts/labels_only_main_rows.py -- do not edit", r"\makeatletter",
 r"\newcommand{\crn}[1]{\ifcsname crn@#1\endcsname\csname crn@#1\endcsname\else\errmessage{Undefined key #1}\fi}"]
for k, v in K.items():
    v = float(v)
    sg = "$-$" if v < 0 else ""
    for suf, s in (("", f3(v)), ("@pct", sg + f"{abs(100*v):.1f}"), ("@1", sg + f"{abs(v):.1f}"), ("@2", sg + f"{abs(v):.2f}"),
                   ("@int", sg + f"{abs(int(round(v)))}")):
        lines.append(rf"\expandafter\def\csname crn@{k}{suf}\endcsname{{{s}}}")
lines.append(r"\makeatother")
(MANU/"camera_ready_numbers.tex").write_text("\n".join(lines)+"\n")
rows = []
for _, r in lo.iterrows():
    b = r.method.split("_B")[1]
    rows.append(f"D$_{{{b}}}$ & {f3(r.ap)} & {f3(r.auroc)} & {f3(r.tpr_at_fpr)} & {f3(r.precision)} & {f3(r.recall)} & {f3(r.f1)} & "
                f"{f2(r.false_alerts_per_week)} & {f3(r.event_detection_rate)} & {f2(r.event_delay_h_mean)} & "
                f"[{f3(r.ap_lo)}, {f3(r.ap_hi)}] & [{f3(r.event_detection_rate_lo)}, {f3(r.event_detection_rate_hi)}] \\\\")
(MANU/"tab_main_extra_rows.tex").write_text("\n".join(rows)+"\n")
print("wrote macros and rows")

# ---- full main table with D rows (bold recomputed over all eight rows)
ref = pd.read_csv(ROOT/"05_RESULTS"/"final"/"tables"/"table_main_none.csv").set_index("method")
allr = [(("A"), ref.loc["stat"]), ("B", ref.loc["iforest"])] + [(f"C$_{{{b}}}$", ref.loc[f"pu_B{b}"]) for b in (8,32,128)] \
       + [(f"D$_{{{b}}}$", lo.set_index("method").loc[f"labels_only_B{b}"]) for b in (8,32,128)]
cols = {"ap":"AP","auroc":"AUC","tpr_at_fpr":r"TPR$_{1\%}$","precision":"Prec.","recall":"Rec.","f1":"F1",
        "false_alerts_per_week":"FA/wk","event_detection_rate":"EDR","event_delay_h_mean":"Delay"}
lower = ("false_alerts_per_week", "event_delay_h_mean")
best = {c: (min if c in lower else max)(float(r[c]) for _, r in allr) for c in cols}
def cell(c, v):
    s = f2(float(v)) if c in lower else f3(float(v))
    return r"\textbf{"+s+"}" if abs(float(v)-best[c]) < 1e-12 else s
body = [name + " & " + " & ".join(cell(c, r[c]) for c in cols) +
        f" & [{f3(r['ap_lo'])}, {f3(r['ap_hi'])}] & [{f3(r['event_detection_rate_lo'])}, {f3(r['event_detection_rate_hi'])}] \\\\"
        for name, r in allr]
tab = [r"\begin{table*}[t]", r"\centering",
 r"\caption{Held-out test results (Sep--Dec 2024) without added missingness. A: robust seasonal statistic; B: Isolation Forest; C: PU logistic regression with weak negatives; D: logistic regression on the labeled hours only (budget $B$ in the subscript). The labeled hours are oracle-curated: $B/2$ injected and $B/2$ non-injected. Means over five authorities (equal weight) of means over five seeds (and five label draws for C and D). AP, AUC and TPR at 1\% FPR are threshold-free ranking metrics; precision, recall, F1, false alerts per authority-week (FA/wk), event detection rate (EDR) and mean detection delay (hours, detected events) use the label-free threshold (98th percentile of validation scores). Best value per column in bold. The last two columns give 95\% two-stage cluster bootstrap intervals for AP and EDR.}",
 r"\label{tab:main}", r"\small", r"\begin{tabular}{@{}l" + "r"*len(cols) + r"cc@{}}", r"\toprule",
 "Detector & " + " & ".join(cols.values()) + r" & AP 95\% CI & EDR 95\% CI \\", r"\midrule", *body, r"\bottomrule", r"\end{tabular}", r"\end{table*}"]
(MANU/"tab_main_cr.tex").write_text("\n".join(tab)+"\n")
print("wrote tab_main_cr.tex")
