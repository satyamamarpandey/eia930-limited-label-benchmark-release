"""Generate LaTeX number macros and tables from saved results (no hand-typed results).

Outputs in 02_MANUSCRIPT_SOURCE/generated/:
  numbers.tex  : \\kn{<key>} lookup; variants <key> (3 dp), <key>@2, <key>@1, <key>@pct, <key>@int
  tab_*.tex    : tables built from 05_RESULTS/final/tables/*.csv and the source manifest
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

CODE = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(CODE))
from gridbench import inject  # noqa: E402
from gridbench.config import load_config, project_paths  # noqa: E402

M = ["stat", "iforest", "pu_B8", "pu_B32", "pu_B128"]
MN = {"stat": "A: Robust seasonal", "iforest": "B: Isolation Forest", "pu_B8": "C: PU-LR, $B{=}8$",
      "pu_B32": "C: PU-LR, $B{=}32$", "pu_B128": "C: PU-LR, $B{=}128$"}
MS = {"stat": "A", "iforest": "B", "pu_B8": "C$_{8}$", "pu_B32": "C$_{32}$", "pu_B128": "C$_{128}$"}
COND = ["none", "mcar5", "mcar15", "block5", "block15"]
CN = {"none": "0\\%", "mcar5": "MCAR 5\\%", "mcar15": "MCAR 15\\%", "block5": "Block 5\\%", "block15": "Block 15\\%"}
FAM = {"spike": "Spike", "level_shift": "Level shift", "drift": "Drift", "flatline": "Flatline", "timing": "Timing"}


def flat(d, prefix=""):
    out = {}
    for k, v in d.items():
        key = f"{prefix}{k}"
        if isinstance(v, dict):
            out.update(flat(v, key + "_"))
        else:
            out[key] = v
    return out


def f3(x):
    return "--" if x is None or (isinstance(x, float) and np.isnan(x)) else f"{x:.3f}"


def f2(x):
    return "--" if x is None or (isinstance(x, float) and np.isnan(x)) else f"{x:.2f}"


def g3(x):
    """3 decimals without the leading zero (dense tables)."""
    return f3(x).replace("0.", ".", 1)


def g2(x):
    return f2(x).replace("0.", ".", 1)


def ci(p, lo, hi, fmt=f3):
    return f"{fmt(p)} [{fmt(lo)}, {fmt(hi)}]"


def bold_max(vals, fmt=f3):
    arr = np.array(vals, float)
    best = np.nanmax(arr)
    return [("\\textbf{" + fmt(v) + "}") if np.isclose(v, best) else fmt(v) for v in arr]


def main():
    cfg = load_config()
    paths = project_paths(cfg)
    R = paths["results"] / "final"
    T = R / "tables"
    G = paths["manuscript"] / "generated"
    G.mkdir(parents=True, exist_ok=True)
    K = json.loads((R / "key_numbers.json").read_text())
    man = json.loads((paths["data"] / "dataset_manifest.json").read_text())

    # extra facts from the source manifest
    for b, r in man["integrity"].items():
        for k, v in r.items():
            if isinstance(v, (int, float)):
                K[f"src_{b}_{k}"] = v
    for b, s in man["split_coverage"].items():
        for sp, r in s.items():
            K[f"split_{b}_{sp}_hours"] = r["hours"]
            K[f"split_{b}_{sp}_invalid"] = r["natural_invalid"]
    for i, f in enumerate(man["files"]):
        K[f"file{i}_rows"] = f["rows"]
        K[f"file{i}_bytes"] = f["bytes"]
        K[f"file{i}_cols"] = f["columns"]
    if "natural" in man:
        for b, r in man["natural"].items():
            for k, v in r.items():
                K[f"nat_{b}_{k}"] = v

    lines = ["% generated by 04_CODE/scripts/make_manuscript_assets.py -- do not edit",
             "\\makeatletter",
             "\\newcommand{\\kn}[1]{\\ifcsname kn@#1\\endcsname\\csname kn@#1\\endcsname"
             "\\else\\errmessage{Undefined result key #1}\\fi}"]
    n = 0
    for k, v in flat(K).items():
        if isinstance(v, bool) or v is None:
            continue
        if isinstance(v, (int, float)) and not (isinstance(v, float) and np.isnan(v)):
            vals = {"": f"{v:.3f}", "@2": f"{v:.2f}", "@1": f"{v:.1f}", "@pct": f"{100 * v:.1f}",
                    "@int": f"{int(round(v)):,}".replace(",", "{,}")}
            for suf, s in vals.items():
                if s.startswith("-"):
                    s = "$-$" + s[1:]
                lines.append(f"\\expandafter\\def\\csname kn@{k}{suf}\\endcsname{{{s}}}")
                n += 1
    lines.append("\\makeatother")
    (G / "numbers.tex").write_text("\n".join(lines) + "\n")

    # ---- Table: dataset
    rows = []
    for b in cfg["data"]["authorities"]:
        r = man["integrity"][b]
        inv = r["demand_blank"] + r["demand_nonpositive"]
        nat = man.get("natural", {}).get(b, {})
        rows.append(f"{b} & {r['rows']:,} & {r['demand_median'] / 1000:.1f} & "
                    f"{r['demand_min'] / 1000:.1f}--{r['demand_max'] / 1000:.1f} & {inv} & "
                    f"{nat.get('exact_repeat_hours', '--')} & "
                    f"{man['split_coverage'][b]['train']['hours']:,}/{man['split_coverage'][b]['val']['hours']:,}/"
                    f"{man['split_coverage'][b]['test']['hours']:,} \\\\")
    tab = ["\\begin{table}[t]", "\\centering", "\\caption{Reported demand in the two EIA-930 BALANCE 2024 files "
           "(hour-ending UTC). CISO: California ISO; ERCO: ERCOT; NYIS: New York ISO; PJM: PJM Interconnection; "
           "SWPP: Southwest Power Pool. Inv.: blank or 0\\,MW hours; Rep.: hours equal to the previous hour's "
           "value.}", "\\label{tab:data}", "\\setlength{\\tabcolsep}{3pt}", "\\footnotesize",
           "\\begin{tabular}{@{}lrrrrrr@{}}", "\\toprule",
           "BA & Hours & Med. & Range & Inv. & Rep. & Train/Val/Test \\\\",
           " & & (GW) & (GW) & (h) & (h) & (h) \\\\", "\\midrule", *rows, "\\bottomrule", "\\end{tabular}",
           "\\end{table}"]
    (G / "tab_data.tex").write_text("\n".join(tab) + "\n")

    # ---- Table: main results (no added missingness)
    d = pd.read_csv(T / "table_main_none.csv").set_index("method").loc[M]
    cols = {"ap": "AP", "auroc": "AUC", "tpr_at_fpr": "TPR$_{1\\%}$", "precision": "Prec.", "recall": "Rec.",
            "f1": "F1", "false_alerts_per_week": "FA/wk", "event_detection_rate": "EDR",
            "event_delay_h_mean": "Delay"}
    body = []
    best = {c: bold_max(d[c].to_numpy(), f2 if c in ("false_alerts_per_week", "event_delay_h_mean") else f3)
            for c in cols}
    # lower is better for FA/wk and delay: bold the minimum instead
    for c in ("false_alerts_per_week", "event_delay_h_mean"):
        arr = d[c].to_numpy(float)
        best[c] = [("\\textbf{" + f2(v) + "}") if np.isclose(v, np.nanmin(arr)) else f2(v) for v in arr]
    for i, m in enumerate(M):
        r = d.loc[m]
        body.append(f"{MS[m]} & " + " & ".join(best[c][i] for c in cols)
                    + f" & [{f3(r.ap_lo)}, {f3(r.ap_hi)}] & "
                      f"[{f3(r.event_detection_rate_lo)}, {f3(r.event_detection_rate_hi)}] \\\\")
    tab = ["\\begin{table*}[t]", "\\centering",
           "\\caption{Held-out test results (Sep--Dec 2024) without added missingness. Means over five authorities "
           "(equal weight) of means over five seeds (and five label draws for C). AP, AUC and TPR at 1\\% FPR are "
           "threshold-free ranking metrics; precision, recall, F1, false alerts per authority-week (FA/wk), event "
           "detection rate (EDR) and mean detection delay (hours, detected events) use the label-free threshold "
           "(98th percentile of validation scores). Best value per column in bold. The last two columns give "
           "95\\% two-stage cluster bootstrap intervals for AP and EDR.}",
           "\\label{tab:main}", "\\small", "\\begin{tabular}{@{}l" + "r" * len(cols) + "cc@{}}", "\\toprule",
           "Detector & " + " & ".join(cols.values()) + " & AP 95\\% CI & EDR 95\\% CI \\\\", "\\midrule", *body,
           "\\bottomrule",
           "\\end{tabular}", "\\end{table*}"]
    (G / "tab_main.tex").write_text("\n".join(tab) + "\n")

    # ---- Table: by condition (AP and AUC)
    c = pd.read_csv(T / "table_by_condition.csv")
    body = []
    for metric, lab in (("ap", "AP"), ("auroc", "ROC-AUC")):
        body.append(f"\\multicolumn{{6}}{{@{{}}l}}{{\\emph{{{lab}}}}} \\\\")
        for m in M:
            r = c[c.method == m].set_index("condition").loc[COND]
            body.append(f"{MS[m]} & " + " & ".join(f3(v) for v in r[metric]) + " \\\\")
    prev = c[c.method == "stat"].set_index("condition").loc[COND, "prevalence"]
    body.append("\\midrule")
    body.append("Prevalence & " + " & ".join(f3(v) for v in prev) + " \\\\")
    tab = ["\\begin{table}[t]", "\\centering",
           "\\caption{Test AP and ROC-AUC by added background missingness (means as in Table~\\ref{tab:main}). "
           "Masked hours are unscored; because masks are drawn independently of the injected faults, positive "
           "prevalence is unchanged across conditions.}",
           "\\label{tab:missing}", "\\setlength{\\tabcolsep}{4pt}", "\\footnotesize",
           "\\begin{tabular}{@{}lrrrrr@{}}", "\\toprule", "Detector & " + " & ".join(CN[x] for x in COND) + " \\\\",
           "\\midrule", *body, "\\bottomrule", "\\end{tabular}", "\\end{table}"]
    (G / "tab_missing.tex").write_text("\n".join(tab) + "\n")

    # ---- Table: fault family
    f = pd.read_csv(T / "table_family_tier_none.csv").set_index("method").loc[M]
    body = []
    for fam in inject.FAMILIES:
        ap = bold_max(f[f"ap_{fam}"].to_numpy(), g3)
        ed = bold_max(f[f"edr_{fam}"].to_numpy(), g2)
        body.append(f"{FAM[fam]} ({K[f'fam_prev_{fam}'] * 100:.2f}\\%) & " + " & ".join(
            f"{a} / {e}" for a, e in zip(ap, ed)) + " \\\\")
    for t in inject.TIERS:
        ap = bold_max(f[f"ap_tier_{t}"].to_numpy(), g3)
        ed = bold_max(f[f"edr_tier_{t}"].to_numpy(), g2)
        body.append(f"Tier: {t} & " + " & ".join(f"{a} / {e}" for a, e in zip(ap, ed)) + " \\\\")
    body.insert(len(inject.FAMILIES), "\\midrule")
    tab = ["\\begin{table}[t]", "\\centering",
           "\\caption{Test AP / event detection rate by fault family and severity tier (0\\% added missingness). "
           "Per-family AP uses that family's altered hours as positives against all non-injected hours; the family's "
           "positive prevalence is in parentheses (the AP of a random ranking).}",
           "\\label{tab:family}", "\\setlength{\\tabcolsep}{2.5pt}", "\\footnotesize",
           "\\begin{tabular}{@{}lrrrrr@{}}", "\\toprule", "Family & " + " & ".join(MS[m] for m in M) + " \\\\",
           "\\midrule", *body, "\\bottomrule", "\\end{tabular}", "\\end{table}"]
    (G / "tab_family.tex").write_text("\n".join(tab) + "\n")

    # ---- Table: paired comparisons + ablations
    p = pd.read_csv(T / "table_paired_differences.csv")
    pr = []
    for a, b in (("pu_B128", "stat"), ("pu_B32", "stat"), ("pu_B8", "stat"), ("iforest", "stat"),
                 ("pu_B128", "iforest"), ("pu_B128", "pu_B8")):
        for metric, lab in (("ap", "AP"), ("event_detection_rate", "EDR")):
            r = p[(p.a == a) & (p.b == b) & (p.metric == metric) & (p.conditions == "none")].iloc[0]
            pr.append(f"{MS[a]} $-$ {MS[b]} & {lab} & {r.mean_diff:+.3f} & [{r.ci_lo:+.3f}, {r.ci_hi:+.3f}] & "
                      f"{int(r.n_ba_positive)}/5 & {r.sign_flip_p:.3f} \\\\")
    tab = ["\\begin{table}[t]", "\\centering",
           "\\caption{Paired differences on matched cells (0\\% added missingness): authority-balanced mean, 95\\% "
           "two-stage cluster bootstrap interval, number of authorities with a positive mean difference, and exact "
           "sign-flip $p$ over the five authority means (minimum attainable $p=0.0625$).}",
           "\\label{tab:paired}", "\\setlength{\\tabcolsep}{3pt}", "\\footnotesize",
           "\\begin{tabular}{@{}llrcrr@{}}", "\\toprule", "Comparison & Metric & $\\Delta$ & 95\\% CI & $+$BA & $p$ \\\\",
           "\\midrule", *pr, "\\bottomrule", "\\end{tabular}",
           "\\end{table}"]
    (G / "tab_paired.tex").write_text("\n".join(tab).replace("+0.", "$+$0.").replace("-0.", "$-$0.") + "\n")

    a = pd.read_csv(T / "table_ablations.csv")
    sel = [("no_residual", "iforest", "none", "B, no residual feats."),
           ("no_residual", "pu_B32", "none", "C$_{32}$, no residual feats."),
           ("no_missing_ind", "iforest", "mcar15", "B, no miss.\\ ind.\\ (M15)"),
           ("no_missing_ind", "pu_B128", "mcar15", "C$_{128}$, no miss.\\ ind.\\ (M15)"),
           ("labels_only", "labels_only_B8", "none", "C$_{8}$, labels only"),
           ("labels_only", "labels_only_B32", "none", "C$_{32}$, labels only"),
           ("labels_only", "labels_only_B128", "none", "C$_{128}$, labels only"),
           ("contam_2", "iforest", "none", "B, contam.\\ 2/family"),
           ("contam_10", "iforest", "none", "B, contam.\\ 10/family"),
           ("contam_10", "pu_B128", "none", "C$_{128}$, contam.\\ 10/family"),
           ("tuned", "stat", "none", "A, val.-label tuning"),
           ("tuned", "iforest", "none", "B, val.-label tuning"),
           ("tuned", "pu_B8", "none", "C$_{8}$, val.-label tuning"),
           ("holdout_flatline", "pu_B32", "none", "C$_{32}$, flatline AP$^{\\dagger}$"),
           ("holdout_spike", "pu_B32", "none", "C$_{32}$, spike AP$^{\\dagger}$")]
    body = []
    for abl, vm, cond, lab in sel:
        r = a[(a.ablation == abl) & (a.variant_method == vm) & (a.condition == cond)].iloc[0]
        body.append(f"{lab} & {f3(r.variant_mean)} & {f3(r.reference_mean)} & "
                    f"{r.mean_diff:+.3f} [{r.ci_lo:+.3f}, {r.ci_hi:+.3f}] & {int(r.n_ba_positive)}/5 \\\\")
    tab = ["\\begin{table}[t]", "\\centering",
           "\\caption{Ablations and sensitivity analyses: test AP of the variant (Var.) and of the primary "
           "configuration (Ref.) on matched authority--seed cells, 0\\% added missingness unless marked M15 (MCAR "
           "15\\%). Contam.: training events per family (primary: 6); these variants re-draw training and test "
           "injections. Val.-label tuning uses validation labels outside the budget. $^{\\dagger}$AP on a family "
           "whose events were excluded from the labeled positives.}",
           "\\label{tab:ablation}", "\\setlength{\\tabcolsep}{2.5pt}", "\\footnotesize",
           "\\begin{tabular}{@{}lrrrr@{}}", "\\toprule", "Variant & Var. & Ref. & $\\Delta$ [95\\% CI] & $+$BA \\\\",
           "\\midrule", *body, "\\bottomrule", "\\end{tabular}", "\\end{table}"]
    (G / "tab_ablation.tex").write_text("\n".join(tab).replace("+0.", "$+$0.").replace("-0.", "$-$0.") + "\n")
    (G / "key_numbers_flat.json").write_text(json.dumps(flat(K), indent=1, default=float))
    print(f"numbers.tex: {n} macros; tables written to {G}")


if __name__ == "__main__":
    main()
